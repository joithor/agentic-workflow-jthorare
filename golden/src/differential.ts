import { decodeText, type Suite } from "./schema.js";

// The scrubber differential (spec §4c, A2): the redaction suite runs each
// corpus input through judge's redactSecrets ("judge/<id>") and `sindri scrub`
// ("sindri/<id>"). The two use different placeholders ([REDACTED] vs
// [REDACTED:kind]), so outputs are compared after mapping both to one token.
// The report names inputs and counts only; it never prints corpus text.
export interface DiffRow {
  id: string;
  judgeHits: number;
  sindriHits: number;
  same: boolean;
}

const PLACEHOLDER = /\[REDACTED(?::[a-z-]+)?\]/g;
const hits = (s: string): number => (s.match(PLACEHOLDER) ?? []).length;

export function redactionDiff(suite: Suite): DiffRow[] {
  const out = new Map<string, { judge?: string; sindri?: string }>();
  for (const c of suite.cases) {
    const m = /^(judge|sindri)\/(.+)$/.exec(c.name);
    if (m === null || c.expect === undefined) continue;
    const side = m[1] as "judge" | "sindri";
    const id = m[2] as string;
    out.set(id, { ...out.get(id), [side]: decodeText(c.expect.stdout) });
  }
  return [...out.entries()]
    .filter(([, v]) => v.judge !== undefined && v.sindri !== undefined)
    .map(([id, v]) => {
      const j = v.judge as string;
      const s = v.sindri as string;
      return { id, judgeHits: hits(j), sindriHits: hits(s), same: j.replace(PLACEHOLDER, "[R]") === s.replace(PLACEHOLDER, "[R]") };
    });
}

export function formatDiff(rows: readonly DiffRow[]): string {
  const differ = rows.filter((r) => !r.same);
  return [
    "# Redaction differential (generated by `golden redaction-diff`)",
    "",
    `${rows.length} corpus inputs; ${differ.length} redact differently in judge (redactSecrets) and sindri (scrub).`,
    "Placeholders are compared as one token; counts are placeholders in each output.",
    "",
    "| input | judge | sindri | same |",
    "|---|---|---|---|",
    ...rows.map((r) => `| ${r.id} | ${r.judgeHits} | ${r.sindriHits} | ${r.same ? "yes" : "**no**"} |`),
    "",
  ].join("\n");
}
